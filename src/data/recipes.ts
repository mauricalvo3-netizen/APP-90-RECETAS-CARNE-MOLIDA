export function getRecipeImageSrc(recipe: SampleRecipe): string {
  const url = recipe.image || recipe.imagen || '';
  if (!url) return '';
  const driveMatch = url.match(/drive\.google\.com\/file\/d\/([^\/\?]+)/);
  if (driveMatch && driveMatch[1]) {
    return `https://lh3.googleusercontent.com/d/${driveMatch[1]}`;
  }
  const driveUcMatch = url.match(/drive\.google\.com\/uc\?.*id=([^\&]+)/);
  if (driveUcMatch && driveUcMatch[1]) {
    return `https://lh3.googleusercontent.com/d/${driveUcMatch[1]}`;
  }
  return url;
}

export function getRecipeMinutes(recipe: SampleRecipe): number {
  if (typeof recipe.tiempoMinutos === 'number' && !isNaN(recipe.tiempoMinutos) && recipe.tiempoMinutos > 0) {
    return recipe.tiempoMinutos;
  }
  const text = recipe.tiempoTexto || recipe.prepTime || '';
  const totalMatch = text.match(/=\s*(\d+)\s*min/i);
  if (totalMatch) return parseInt(totalMatch[1], 10);
  const minMatch = text.match(/(\d+)\s*min/i);
  if (minMatch) return parseInt(minMatch[1], 10);
  return 0;
}

